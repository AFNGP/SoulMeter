inline VOID SWDecryptBody(const BYTE* frame, BYTE* body, const UINT bodySize, const BYTE* keyTable) {

	if (frame == nullptr || body == nullptr || bodySize == 0 || keyTable == nullptr)
		return;

	const UINT row = 16 * (frame[SWCRYPT_OFF_SEQ] & 0xF);

	switch (frame[SWCRYPT_OFF_MODE]) {
	case SWCRYPT_MODE_XOR:
		for (UINT i = 0; i < bodySize; i++)
			body[i] ^= keyTable[row + (i & 0xF)];
		break;

	case SWCRYPT_MODE_AES: {
		// nonce(4) flag(1) seq(1) size(2) "SWPK", then the CTR block counter.
		BYTE iv[16] = { 0 };
		memcpy(iv, frame + SWCRYPT_OFF_NONCE, 4);
		iv[4] = frame[SWCRYPT_OFF_FLAG];
		iv[5] = frame[SWCRYPT_OFF_SEQ];
		memcpy(iv + 6, frame + SWCRYPT_OFF_SIZE, 2);
		memcpy(iv + 8, "SWPK", 4);

		EVP_CIPHER_CTX* ctx = EVP_CIPHER_CTX_new();
		if (ctx == nullptr)
			break;

		INT32 outSize = 0;
		if (EVP_DecryptInit_ex(ctx, EVP_aes_128_ctr(), nullptr, SWCRYPT_AESKEYTABLE + row, iv) == 1)
			EVP_DecryptUpdate(ctx, body, &outSize, body, (INT32)bodySize);

		EVP_CIPHER_CTX_free(ctx);
		break;
	}

	default:
		break;
	}
}
